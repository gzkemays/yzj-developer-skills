#!/usr/bin/env python3
"""commit_guard.py 回归用例。改动脚本后运行：python scripts/test-commit-guard.py（全部通过退出 0）。

脚本只有一个门禁——提交信息与 MR 文本不带 AI 记号 / 进度词（git-commit 铁律 3）；分支、授权不在机械检查范围内。
用例按 commit-msg（硬门禁）与 pretooluse（早期预检）两层组织；pretooluse 不解析 shell，任何写法都按全文扫描。
"""
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

GUARD = Path(__file__).resolve().parent.parent / "common/skills/git-commit/scripts/commit_guard.py"

# (名称, 提交信息, 期望是否拦截)
MSG_CASES = [
    ("干净 feat", "feat: 新增订单导出\n\n* 支持按月份筛选\n", False),
    ("协作者尾注", "feat: x\n\nCo-Authored-By: Someone <a@b.com>\n", True),
    ("来源尾注", "feat: x\n\nGenerated with internal tooling\n", True),
    ("模型名", "fix: 修复 Claude 返回空", True),
    ("紧贴中文模型名", "opt: 由Claude生成的脚本整理", True),
    ("emoji", "feat: x 🤖", True),
    ("AI 署名句尾", "feat: x\n\n由 AI 生成", True),
    ("AI 业务名词不拦", "feat: 新增 AI 辅助诊断模块", False),
    ("进度词", "fix: Step 3 修复登录", True),
    ("路径语境不算", "opt: 更新 .claude/settings.json 与 claude-settings-hooks.json", False),
    ("业务词 opus 不算", "feat: magnum opus 展示页", False),
    ("全大写模型名", "fix: CLAUDE 输出修正", True),
    ("入口文件名不算", "opt: 更新 CLAUDE.md 与 AGENTS.md", False),
    ("型号写法", "opt: 切到 claude-sonnet-4.5", True),
    ("域名写法", "opt: 参考 claude.ai 与 anthropic.com", True),
    ("编辑器注释块忽略", "feat: x\n# Please enter the commit message\n# Claude\n", False),
]

# (名称, tool_name, 命令, 期望 deny)
HOOK_CASES = [
    ("开发分支干净提交", "Bash", 'git commit -m "feat: x"', False),
    ("主干干净提交不拦（分支不在机械检查范围）", "Bash", 'git checkout master && git commit -m "feat: x"', False),
    ("非提交命令放行", "Bash", 'echo "Claude"', False),
    ("Claude Code 默认 heredoc 写法干净不弹", "Bash", "git commit -m \"$(cat <<'EOF'\nfeat: x\nEOF\n)\"", False),
    ("heredoc 带尾注", "Bash", "git commit -m \"$(cat <<'EOF'\nfeat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>\nEOF\n)\"", True),
    ("花括号包裹", "Bash", '{ git commit -m "Generated with Claude"; }', True),
    ("if 包裹", "Bash", 'if true; then git commit -m "feat: x Claude"; fi', True),
    ("timeout / winpty 包装", "Bash", 'timeout 30 winpty git commit -m "Generated by tool"', True),
    ("行尾注释后换行", "Bash", 'git status # check\ngit commit -m "feat: x\n\nGenerated with Claude Code"', True),
    ("命令替换", "Bash", "out=\"$(git commit -m 'Generated with Claude' 2>&1)\"", True),
    ("bash -lc", "Bash", "bash -lc 'git commit -m \"feat: x Claude\"'", True),
    ("长选项缩写", "Bash", 'git commit --mess "feat: x Generated with Claude"', True),
    ("printf 字面 \\n 尾注", "Bash", "printf 'feat: x\\n\\nCo-authored-by: Bob <b@x.com>\\n' | git commit -F -", True),
    ("同命令写文件再 -F", "Bash", "printf 'feat: x\\nGenerated with Claude\\n' > msg.txt && git commit -F msg.txt", True),
    ("作者身份", "Bash", 'git commit --author="Claude <a@b>" -m "feat: x"', True),
    ("PowerShell 通道", "PowerShell", 'git commit -m "feat: x`n`nGenerated with Claude"', True),
    ("Windows 路径里的 claude 不算", "PowerShell", r'git commit -F C:\Users\me\AppData\Local\Temp\claude\s1\msg.txt', False),
    ("Git Bash 路径里的 claude 不算", "Bash", "git commit -F /c/Users/me/AppData/Local/Temp/claude/s1/msg.txt", False),
    ("其他工具不查", "Read", 'git commit -m "Claude"', False),
    ("gh pr create 尾注", "Bash", 'gh pr create --title "feat: x" --body "x\n\n🤖 Generated with tooling"', True),
    ("gh pr create 干净", "Bash", 'gh pr create --title "feat: x" --body "背景 / 改动 / 验证"', False),
    ("glab mr create 尾注", "Bash", 'glab mr create -t "feat: x" -d "Generated by tool"', True),
    ("curl 调 merge_requests", "Bash", 'curl -X POST -d "title=feat: x Claude" https://git.example.com/api/v4/projects/1/merge_requests', True),
    ("PowerShell 调 pulls", "PowerShell", 'Invoke-RestMethod -Method Post -Uri https://api.example.com/repos/a/b/pulls -Body \'{"body":"Generated with tool"}\'', True),
    ("curl 非 MR 接口不查", "Bash", 'curl -d "Claude" https://example.com/api/issues', False),
    ("gh pr list 不查", "Bash", 'gh pr list --search "Claude"', False),
]


def run_hook(tool, command, cwd):
    payload = json.dumps({"tool_name": tool, "tool_input": {"command": command}, "cwd": cwd})
    p = subprocess.run([sys.executable, str(GUARD), "pretooluse"], input=payload.encode("utf-8"), capture_output=True)
    out = p.stdout.decode("utf-8", "replace").strip()
    return p.returncode, (json.loads(out)["hookSpecificOutput"]["permissionDecision"] if out else "allow")


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    bad = 0
    with tempfile.TemporaryDirectory() as d:
        msg = Path(d) / "COMMIT_EDITMSG"
        for name, text, expect in MSG_CASES:
            msg.write_text(text, encoding="utf-8")
            rc = subprocess.run([sys.executable, str(GUARD), "commit-msg", str(msg)], capture_output=True).returncode
            ok = (rc == 1) == expect
            bad += not ok
            print(f"{'OK' if ok else 'XX'} commit-msg  {name}: rc={rc}")
        # -F 引用已存在文件：读入文件内容检查
        (Path(d) / "dirty.txt").write_text("feat: x\n\nGenerated with Claude\n", encoding="utf-8")
        cases = HOOK_CASES + [
            ("-F 已存在文件带尾注", "Bash", "git commit -F dirty.txt", True),
            ("gh pr --body-file 带尾注", "Bash", 'gh pr create --title "feat: x" --body-file dirty.txt', True),
            ("gh pr -F 带尾注", "Bash", 'gh pr create -t "feat: x" -F dirty.txt', True),
            ("curl @文件 带尾注", "Bash", "curl -X POST --data @dirty.txt https://git.example.com/api/v4/projects/1/merge_requests", True),
            ("gh api -F body=@文件 带尾注", "Bash", "gh api repos/a/b/pulls -f title=x -F body=@dirty.txt", True),
        ]
        for name, tool, cmd, expect in cases:
            rc, dec = run_hook(tool, cmd, d)
            ok = rc == 0 and (dec == "deny") == expect
            bad += not ok
            print(f"{'OK' if ok else 'XX'} pretooluse  {name}: {dec}")
    # fail-open：坏输入不阻塞
    for raw in ["", "not json", "[]"]:
        p = subprocess.run([sys.executable, str(GUARD), "pretooluse"], input=raw.encode(), capture_output=True)
        ok = p.returncode == 0 and not p.stdout.strip()
        bad += not ok
        print(f"{'OK' if ok else 'XX'} fail-open   {raw!r}: rc={p.returncode}")
    total = len(MSG_CASES) + len(cases) + 3
    print(f"\n{total - bad}/{total} 通过")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
